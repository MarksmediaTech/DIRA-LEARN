-- ============ 5. self-check: abort if any rule is broken ============
do $check$
declare bad text;
begin
  select string_agg(table_name || ' ' || privilege_type, ', ') into bad from information_schema.table_privileges
   where table_schema = 'public' and grantee = 'anon';
  if bad is not null then raise exception 'migration 38 self-check: signed-out visitors have table privileges: %', bad; end if;

  select string_agg(table_name || ' ' || privilege_type, ', ') into bad from information_schema.table_privileges
   where table_schema = 'public' and grantee = 'authenticated' and privilege_type not in ('SELECT', 'INSERT', 'UPDATE', 'DELETE');
  if bad is not null then raise exception 'migration 38 self-check: signed-in users have %', bad; end if;

  select string_agg(c.relname, ', ') into bad from pg_class c
   where c.relnamespace = 'public'::regnamespace and c.relkind in ('r', 'p') and not c.relrowsecurity
     and (has_table_privilege('authenticated', c.oid, 'select') or has_table_privilege('anon', c.oid, 'select'));
  if bad is not null then raise exception 'migration 38 self-check: tables without RLS are reachable: %', bad; end if;

  select string_agg(tp.table_name || ' ' || tp.privilege_type, ', ') into bad from information_schema.table_privileges tp
   join pg_class c on c.relname = tp.table_name and c.relnamespace = 'public'::regnamespace and c.relkind in ('r', 'p')
   where tp.table_schema = 'public' and tp.grantee = 'authenticated'
     and not exists (select 1 from pg_policies p where p.schemaname = 'public' and p.tablename = tp.table_name and p.permissive = 'PERMISSIVE'
                      and p.roles && array['authenticated', 'public']::name[] and (p.cmd = 'ALL' or p.cmd = tp.privilege_type));
  if bad is not null then raise exception 'migration 38 self-check: privileges without a matching RLS policy: %', bad; end if;

  if not has_table_privilege('authenticated', 'public.profiles', 'select') then
    raise exception 'migration 38 self-check: signed-in users cannot read public.profiles';
  end if;
  select string_agg(p.proname, ', ') into bad from pg_proc p
   where p.pronamespace = 'public'::regnamespace and p.prorettype not in ('trigger'::regtype, 'event_trigger'::regtype)
     and has_function_privilege('anon', p.oid, 'execute') and p.proname not in ('check_request', 'verify_certificate');
  if bad is not null then raise exception 'migration 38 self-check: signed-out visitors can call %', bad; end if;
  select string_agg(p.proname, ', ') into bad from pg_proc p
   where p.pronamespace = 'public'::regnamespace and has_function_privilege('authenticated', p.oid, 'execute')
     and p.proname in ('claim_first_admin', 'apply_digital_marketing_approval_37', 'claim_emails', 'claim_file_scans', 'record_file_scan',
                       'connect_retention_purge', 'publish_due_briefs', 'load_curriculum_v13', 'seed_initial_topic_proposals');
  if bad is not null then raise exception 'migration 38 self-check: server-only functions callable by signed-in users: %', bad; end if;
  raise notice 'migration 38: explicit grants in place; self-check passed';
end $check$;
