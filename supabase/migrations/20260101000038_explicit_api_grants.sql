insert into grants_38_backup(object_kind, object_name, grantee, privilege)
select 'relation', c.oid::regclass::text, coalesce(r.rolname, 'PUBLIC'), a.privilege_type
  from pg_class c cross join lateral aclexplode(c.relacl) a left join pg_roles r on r.oid = a.grantee
 where c.relnamespace = 'public'::regnamespace and c.relkind in ('r', 'p', 'v', 'm', 'S') and c.relname <> 'grants_38_backup'
   and coalesce(r.rolname, 'PUBLIC') in ('anon', 'authenticated', 'service_role', 'PUBLIC')
union all
select 'function', p.oid::regprocedure::text, coalesce(r.rolname, 'PUBLIC'), a.privilege_type
  from pg_proc p cross join lateral aclexplode(coalesce(p.proacl, acldefault('f', p.proowner))) a left join pg_roles r on r.oid = a.grantee
 where p.pronamespace = 'public'::regnamespace and coalesce(r.rolname, 'PUBLIC') in ('anon', 'authenticated', 'service_role', 'PUBLIC')
on conflict do nothing;

