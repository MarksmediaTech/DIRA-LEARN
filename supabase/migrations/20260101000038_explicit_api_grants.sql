-- Migration 38 - explicit Data API grants (21 Nov 2026).
-- WHY: in production every signed-in request to public.profiles returned 403 ("permission denied for table profiles"),
-- although the profile existed with role super_admin and status active. Cause: migrations 01-37 never granted table
-- privileges to the API roles; they relied on Supabase granting every new public table, sequence and function to anon,
-- authenticated and service_role automatically. Supabase stopped doing that (new projects since 30 May 2026, all
-- projects since 30 Oct 2026). Reproduced locally on 21 Nov 2026: 5 of 106 tables readable by signed-in users.
-- WHAT: writes the authored intent of migrations 01-37 down as explicit grants (generated by
-- tools/release/generate_grants_38.py, reviewed):
--   * signed-in users (authenticated): only SELECT/INSERT/UPDATE/DELETE that a permissive RLS policy allows and that the
--     earlier migrations did not deliberately withhold. RLS stays on everywhere and still decides WHICH ROWS. Never
--     TRUNCATE, REFERENCES or TRIGGER (the old automatic defaults granted those too; they are removed here).
--   * signed-out visitors (anon): no table at all; only check_request() (API pre-request check) and verify_certificate().
--   * service_role (Edge Functions, server only): all tables, sequences and functions in public.
--   * functions: execute exactly as authored (122 for signed-in users; the 26 internal ones stay server-only).
-- SAFE on both kinds of project: on a project that still had the old automatic grants it narrows them to the intent; on
-- a new-style project it adds the missing grants. No data, row, policy or function body is changed.
-- SELF-CHECK at the end: the migration aborts (and changes nothing) if the result breaks any rule above.
-- Rollback: supabase/rollback/20260101000038_explicit_api_grants_down.sql restores the privileges recorded below exactly.

