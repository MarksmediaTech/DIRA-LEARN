#!/usr/bin/env python3
"""Build supabase/production_init/01_initialize_production.sql from the repository migrations, unchanged.

Usage: python3 supabase/production_init/build_bundle.py      (run from the project folder)

The bundle is for psql (it uses \\set and \\echo). It:
  * stops before changing anything if public.profiles already exists, if the public schema has any table, or if
    supabase_migrations already records migrations (so it can never run twice or over an existing schema);
  * runs every migration file 01..39 in its own transaction, exactly as `supabase db push` does, and records it in
    supabase_migrations.schema_migrations in the SAME transaction, so a stop half-way leaves a consistent history
    and the CLI (`supabase migration list` / `db push`) sees the same state;
  * runs seed.sql (reference data only) in one transaction;
  * never touches auth.users rows, passwords or sessions; migration 36 gives each existing account its applicant profile;
  * migration 37 approves nothing: it places the Digital Marketing topic proposals on their V13.2 sessions;
  * migration 38 writes the Data API grants explicitly (Supabase no longer grants new tables automatically);
  * migration 39 gives Super Administrators interim safeguarding access until a Lead or Deputy is appointed.
It also writes 01b_continue_after_37.sql for a database where 01-37 are already applied but the seed did not complete.
The SHA-256 of every source file is written into the header so the bundle can be checked against the repository.
"""
import hashlib, pathlib, re, sys

root = pathlib.Path(__file__).resolve().parents[2]
mig_dir = root / 'supabase' / 'migrations'
seed = root / 'supabase' / 'seed.sql'
out = root / 'supabase' / 'production_init' / '01_initialize_production.sql'

files = sorted(mig_dir.glob('*.sql'))
pat = re.compile(r'^(\d{14})_([a-z0-9_]+)\.sql$')
if len(files) != 39 or not all(pat.match(f.name) for f in files):
    sys.exit(f'expected 39 migration files named <14 digits>_<name>.sql, found {len(files)}')
for f in files + [seed]:
    body = f.read_text(encoding='utf-8')
    if re.search(r'^\s*(begin|commit|rollback|start transaction)\s*;', body, re.I | re.M):
        sys.exit(f'{f.name} contains its own transaction control; the bundle would break it')
    if re.search(r'^\s*\\', body, re.M):
        sys.exit(f'{f.name} contains a psql meta-command')

def sha(p): return hashlib.sha256(p.read_bytes()).hexdigest()
def lit(s): return "'" + s.replace("'", "''") + "'"

parts = []
parts.append(f"""-- DIRA LEARN - production initialization, STEP 1 (generated by build_bundle.py - do not edit by hand)
-- Source: supabase/migrations 01-39 and supabase/seed.sql, byte-for-byte; nothing else is added except the guard,
-- the transaction boundaries and the migration-history rows.
-- Run ONLY with psql, ONLY after 00_precheck_readonly.sql said SAFE_TO_INITIALIZE and a backup was taken:
--   psql "<session-pooler connection string>" -v ON_ERROR_STOP=1 -X -f supabase/production_init/01_initialize_production.sql
-- Each migration is its own transaction. If one fails, psql stops; everything before it stays applied and recorded,
-- nothing of the failing one remains. Do not re-run the whole bundle then: send the error to Claude.
--
-- Source files (SHA-256):
""")
for f in files + [seed]:
    parts.append(f"--   {sha(f)}  {f.relative_to(root).as_posix()}\n")
parts.append(r"""
\set ON_ERROR_STOP on
\set QUIET on
\echo '== guard: checking that the database is not initialized yet'
do $guard$
declare n_tables int; n_hist int := 0;
begin
  if to_regclass('public.profiles') is not null then
    raise exception 'STOP: public.profiles already exists. This bundle is only for an empty database. Nothing was changed.';
  end if;
  select count(*) into n_tables from pg_class c join pg_namespace s on s.oid = c.relnamespace
   where s.nspname = 'public' and c.relkind in ('r', 'p', 'v', 'm');
  if n_tables > 0 then
    raise exception 'STOP: the public schema already has % table(s)/view(s). Run 00_precheck_readonly.sql and send it to Claude. Nothing was changed.', n_tables;
  end if;
  if to_regclass('supabase_migrations.schema_migrations') is not null then
    execute 'select count(*) from supabase_migrations.schema_migrations' into n_hist;
  end if;
  if n_hist > 0 then
    raise exception 'STOP: supabase_migrations already records % migration(s). Nothing was changed.', n_hist;
  end if;
  if exists (select 1 from pg_trigger where tgrelid = 'auth.users'::regclass and not tgisinternal) then
    raise exception 'STOP: auth.users already has a trigger (%). Run 00_precheck_readonly.sql and send it to Claude. Nothing was changed.',
      (select string_agg(tgname, ', ') from pg_trigger where tgrelid = 'auth.users'::regclass and not tgisinternal);
  end if;
  if exists (select 1 from storage.buckets where id in ('application-documents', 'connect-attachments', 'course-materials',
                                                       'learning-resources', 'project-evidence', 'submissions')) then
    raise exception 'STOP: a DIRA LEARN storage bucket already exists. Run 00_precheck_readonly.sql and send it to Claude. Nothing was changed.';
  end if;
  raise notice 'guard passed: % sign-in account(s) exist and will be kept', (select count(*) from auth.users);
end $guard$;

begin;
create schema if not exists supabase_migrations;
create table if not exists supabase_migrations.schema_migrations (version text not null primary key, statements text[], name text);
commit;
""")
for f in files:
    version, name = pat.match(f.name).groups()
    body = f.read_text(encoding='utf-8')
    if not body.endswith('\n'): body += '\n'
    parts.append(f"\n\\echo '== migration {version} {name}'\nbegin;\n")
    parts.append(body)
    parts.append(f";\ninsert into supabase_migrations.schema_migrations(version, name) values ({lit(version)}, {lit(name)});\ncommit;\n")
body = seed.read_text(encoding='utf-8')
if not body.endswith('\n'): body += '\n'
parts.append("\n\\echo '== seed.sql (reference data: organisation, programme, roles, settings, tracks, curriculum drafts)'\nbegin;\n")
parts.append(body)
parts.append(""";\ncommit;
\\echo '== done: run 02_verify_readonly.sql next'
\\set QUIET off
select (select count(*) from supabase_migrations.schema_migrations) as migrations_recorded,
       (select count(*) from auth.users) as sign_in_accounts,
       (select count(*) from public.profiles) as profiles,
       (select count(*) from auth.users u where not exists (select 1 from public.profiles p where p.id = u.id)) as accounts_without_profile,
       (select count(*) from public.profiles where role <> 'applicant') as profiles_above_applicant;
""")
out.write_text(''.join(parts), encoding='utf-8')

# ---------------- 01b: continue a database where migrations 01-37 are applied but the seed did not complete ----------------
out_b = root / 'supabase' / 'production_init' / '01b_continue_after_37.sql'
later = files[37:]   # migrations 38 onward
assert pat.match(later[0].name).group(1) == '20260101000038', later[0].name
b = [f"""-- DIRA LEARN - production initialization, STEP 1b (generated by build_bundle.py - do not edit by hand)
-- For a database where migrations 01-37 are applied and recorded but the seed did not complete (state found in
-- production on 21 Nov 2026: 403 on /rest/v1/profiles, no organisation/programme/curriculum data).
-- Contents, byte for byte from the repository: migrations 38-{len(later) + 37} (38: explicit Data API grants; 39: interim
-- safeguarding access for Super Administrators) and seed.sql.
-- Run ONLY with psql, ONLY after 00b_precheck_partial_readonly.sql said CONTINUE and a backup was taken:
--   psql "<session-pooler connection string>" -v ON_ERROR_STOP=1 -X -f supabase/production_init/01b_continue_after_37.sql
-- It changes no sign-in account, password, profile role or existing record. The seed only adds missing reference and
-- curriculum rows (it is safe to re-run; a second run changes nothing).
{chr(10).join(f'--   {sha(m)}  {m.relative_to(root).as_posix()}' for m in later)}
--   {sha(seed)}  supabase/seed.sql
\\set ON_ERROR_STOP on
\\set QUIET on
\\echo '== guard: migrations 01-37 recorded, 38 onward not yet'
do $guard$
declare v text;
begin
  if to_regclass('supabase_migrations.schema_migrations') is null then
    raise exception 'STOP: no migration history. Use 01_initialize_production.sql for an empty database. Nothing was changed.';
  end if;
  execute 'select string_agg(version, '','' order by version) from supabase_migrations.schema_migrations' into v;
  if v is distinct from (select string_agg(to_char(20260101000000 + g, 'FM00000000000000'), ',' order by g) from generate_series(1, 37) g) then
    raise exception 'STOP: migration history is not exactly 01-37 (found %). Run 00b_precheck_partial_readonly.sql and send it to Claude. Nothing was changed.', coalesce(v, 'none');
  end if;
  if to_regclass('public.profiles') is null then
    raise exception 'STOP: public.profiles does not exist although 01-37 are recorded. Nothing was changed.';
  end if;
  raise notice 'guard passed: % sign-in account(s) and % profile(s) will be kept', (select count(*) from auth.users), (select count(*) from public.profiles);
end $guard$;
"""]
for m in later:
    v, n = pat.match(m.name).groups()
    body = m.read_text(encoding='utf-8')
    if not body.endswith('\n'): body += '\n'
    b.append(f"\n\\echo '== migration {v} {n}'\nbegin;\n" + body + f";\ninsert into supabase_migrations.schema_migrations(version, name) values ({lit(v)}, {lit(n)});\ncommit;\n")
sb = seed.read_text(encoding='utf-8')
if not sb.endswith('\n'): sb += '\n'
b.append("\n\\echo '== seed.sql (reference data and curriculum drafts; idempotent)'\nbegin;\n" + sb + ";\ncommit;\n")
b.append("""\\echo '== done: run 02_verify_readonly.sql next'
\\set QUIET off
select (select count(*) from supabase_migrations.schema_migrations) as migrations_recorded,
       has_table_privilege('authenticated', 'public.profiles', 'select') as profiles_readable_by_signed_in_users,
       (select count(*) from public.organizations) as organizations, (select count(*) from public.programmes) as programmes,
       (select count(*) from public.tracks) as tracks, (select count(*) from public.curriculum_sessions) as sessions,
       (select count(*) from auth.users) as sign_in_accounts,
       (select count(*) from auth.users u where not exists (select 1 from public.profiles p where p.id = u.id)) as accounts_without_profile;
""")
out_b.write_text(''.join(b), encoding='utf-8')
print(f'wrote {out_b.relative_to(root)}: migrations 38-{len(later) + 37} + seed, {out_b.stat().st_size} bytes, sha256 {sha(out_b)}')

print(f'wrote {out.relative_to(root)}: {len(files)} migrations + seed, {out.stat().st_size} bytes, sha256 {sha(out)}')
