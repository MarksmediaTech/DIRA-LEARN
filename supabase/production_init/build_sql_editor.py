#!/usr/bin/env python3
"""Builds the Supabase Dashboard SQL Editor version of the production initialization (21 Nov 2026).

Usage: python3 supabase/production_init/build_sql_editor.py      (from the project folder)

Writes supabase/production_init/sql_editor/:
  STEP-0  read-only pre-check (= 00_precheck_readonly.sql)
  STEP-1 .. STEP-6  migrations 01-39 and seed.sql, unchanged and in order, in six parts small enough to paste
  STEP-7  read-only verification (= 02_verify_readonly.sql)
  STEP-8  first Super Administrator for an existing, confirmed sign-in account
No psql commands. Each part is ONE transaction: the SQL Editor sends the whole text as a single query, which PostgreSQL
runs as one implicit transaction, so a part either applies completely or not at all (an error rolls everything in the
part back). For that reason the parts contain no BEGIN/COMMIT of their own. Part 1 ends with migration 15, which adds the
role values 'founder' and 'co_founder': PostgreSQL only lets later statements use new enum values after a commit.
Each part starts with a guard that refuses to run unless exactly the previous parts are recorded, and records its own
migrations in supabase_migrations.schema_migrations (the table the Supabase CLI uses), in the same transaction.
"""
import hashlib, pathlib, re, sys

root = pathlib.Path(__file__).resolve().parents[2]
mig_dir, seed = root / 'supabase' / 'migrations', root / 'supabase' / 'seed.sql'
pi = root / 'supabase' / 'production_init'; out_dir = pi / 'sql_editor'
files = sorted(mig_dir.glob('*.sql'))
pat = re.compile(r'^(\d{14})_([a-z0-9_]+)\.sql$')
if len(files) != 39 or not all(pat.match(f.name) for f in files): sys.exit(f'expected 39 migrations, found {len(files)}')
for f in files + [seed]:
    body = f.read_text(encoding='utf-8')
    if re.search(r'^\s*(begin|commit|rollback|start transaction|end)\s*;|^\s*(savepoint|release)\s+\w+\s*;', body, re.I | re.M): sys.exit(f'{f.name}: own transaction control')
    if re.search(r'^\s*\\', body, re.M): sys.exit(f'{f.name}: psql meta-command')
    if re.search(r'\badd value\b', body, re.I) and f.name[12:14] != '15': sys.exit(f'{f.name}: adds an enum value outside migration 15 (part boundaries must be revised)')

PARTS = [(1, 15), (16, 29), (30, 30), (31, 31), (32, 32), (33, 39)]
assert [n for a, b in PARTS for n in range(a, b + 1)] == list(range(1, 40))
sha = lambda p: hashlib.sha256(p.read_bytes()).hexdigest()
lit = lambda s: "'" + s.replace("'", "''") + "'"
ver = lambda n: f'{20260101000000 + n}'
BUCKETS = "'application-documents', 'connect-attachments', 'course-materials', 'learning-resources', 'project-evidence', 'submissions'"
# Line endings (found 21 Nov 2026): copying a file from Notepad into the browser stores Windows line breaks (CR LF) in
# every function body. Migrations 17, 19, 20, 23, 33, 34 and 36 change existing functions by searching their stored text for
# phrases that contain a plain LF, so with CR LF they stop ("Migration 20: expected text not found in function
# guard_submission()"). The SQL Editor parts therefore re-create every function whose stored source contains a CR, with the
# CRs removed, before each of those migrations and at the end of every part. With plain LF it does nothing. The migration
# files themselves are not changed.
NORMALIZE = '''
-- ----- line-ending normalisation (SQL Editor installation only; does nothing when the text has plain LF line breaks) -----
do $crlf$
declare r record;
begin
  for r in select p.oid from pg_proc p where p.pronamespace = 'public'::regnamespace and p.prokind in ('f', 'p') and position(chr(13) in p.prosrc) > 0 loop
    execute replace(pg_get_functiondef(r.oid), chr(13), '');
  end loop;
end $crlf$;
'''
PATCHING = {f.name for f in files if 'pg_get_functiondef' in f.read_text(encoding='utf-8')}
out_dir.mkdir(exist_ok=True)
for old in out_dir.glob('STEP-*.sql'): old.unlink()

def header(step, title, lines):
    return '\n'.join([f'-- DIRA LEARN - Supabase SQL Editor installation, STEP {step}: {title}',
                      '-- Generated by supabase/production_init/build_sql_editor.py from the repository files - do not edit by hand.',
                      '-- How to run: Supabase Dashboard -> SQL Editor -> New query -> paste ALL of this file -> Run.',
                      '-- Full instructions: docs/deployment/SQL_EDITOR_INITIALIZATION.md'] + [f'-- {l}' for l in lines]) + '\n'

for k, (a, b) in enumerate(PARTS, 1):
    part = files[a - 1:b]; last = k == len(PARTS)
    src = part + ([seed] if last else [])
    lines = [f'Part {k} of 6: migrations {a:02d}-{b:02d}' + (' and seed.sql' if last else '') + '. One transaction: it applies completely or not at all.',
             'Contents, byte for byte (SHA-256):'] + [f'  {sha(f)}  {f.relative_to(root).as_posix()}' for f in src]
    s = [header(k, f'part {k} of 6 (migrations {a:02d}-{b:02d}' + (' + seed' if last else '') + ')', lines), '']
    expected_before = ','.join(ver(n) for n in range(1, a))
    s.append(f"""do $guard$
declare v text; n int;
begin
  if to_regclass('supabase_migrations.schema_migrations') is not null then
    execute 'select string_agg(version, '','' order by version) from supabase_migrations.schema_migrations' into v;
  end if;
  if coalesce(v, '') <> {lit(expected_before)} then
    raise exception 'STOP: this is part {k} of 6, but the database records %. {"Run STEP-0 and send its result to Claude." if k == 1 else f"Run the parts in order: part {k-1} must be completed first, and each part only once."} Nothing was changed.',
      coalesce('migrations ' || v, 'no migrations');
  end if;""")
    if k == 1:
        s.append(f"""  if to_regclass('public.profiles') is not null then
    raise exception 'STOP: public.profiles already exists. This installation is only for an empty database. Nothing was changed.';
  end if;
  select count(*) into n from pg_class c join pg_namespace s on s.oid = c.relnamespace where s.nspname = 'public' and c.relkind in ('r', 'p', 'v', 'm');
  if n > 0 then raise exception 'STOP: the public schema already has % table(s)/view(s). Run STEP-0 and send it to Claude. Nothing was changed.', n; end if;
  if exists (select 1 from pg_trigger where tgrelid = 'auth.users'::regclass and not tgisinternal) then
    raise exception 'STOP: auth.users already has a trigger. Run STEP-0 and send it to Claude. Nothing was changed.';
  end if;
  if exists (select 1 from storage.buckets where id in ({BUCKETS})) then
    raise exception 'STOP: a DIRA LEARN storage bucket already exists. Run STEP-0 and send it to Claude. Nothing was changed.';
  end if;""")
    s.append("end $guard$;\n")
    if k == 1:
        s.append("create schema if not exists supabase_migrations;\n"
                 "create table if not exists supabase_migrations.schema_migrations (version text not null primary key, statements text[], name text);\n")
    for f in part:
        v, n = pat.match(f.name).groups()
        if f.name in PATCHING: s.append(NORMALIZE)
        body = f.read_text(encoding='utf-8')
        if not body.endswith('\n'): body += '\n'
        s.append(f"\n-- >>>>> migration {v} {n} (begin of file, unchanged)\n{body}-- <<<<< migration {v} {n} (end of file)\n;\n"
                 f"insert into supabase_migrations.schema_migrations(version, name) values ({lit(v)}, {lit(n)});\n")
    s.append(NORMALIZE)
    if last:
        body = seed.read_text(encoding='utf-8')
        if not body.endswith('\n'): body += '\n'
        s.append(f"\n-- >>>>> seed.sql (begin of file, unchanged)\n{body}-- <<<<< seed.sql (end of file)\n;\n")
        s.append(NORMALIZE)
        s.append("""
-- result shown in the SQL Editor
select 'Part 6 of 6 completed: migrations 01-39 and the seed are installed. Next: STEP-7 (verification).' as result,
       (select count(*) from supabase_migrations.schema_migrations) as migrations_recorded,
       (select count(*) from public.organizations) as organisations, (select count(*) from public.programmes) as programmes,
       (select count(*) from public.tracks) as tracks, (select count(*) from public.curriculum_sessions) as sessions,
       (select count(*) from auth.users) as sign_in_accounts,
       (select count(*) from auth.users u where not exists (select 1 from public.profiles p where p.id = u.id)) as accounts_without_profile,
       has_table_privilege('authenticated', 'public.profiles', 'select') as profiles_readable_by_signed_in_users;
""")
    else:
        s.append(f"""
-- result shown in the SQL Editor
select 'Part {k} of 6 completed: migrations {a:02d}-{b:02d} installed. Next: STEP-{k + 1}.' as result,
       (select count(*) from supabase_migrations.schema_migrations) as migrations_recorded;
""")
    name = f'STEP-{k}_part-{k}-of-6_migrations-{a:02d}-{b:02d}' + ('_and-seed' if last else '') + '.sql'
    (out_dir / name).write_text(''.join(s), encoding='utf-8')

def copy(step, title, src, extra):
    body = src.read_text(encoding='utf-8')
    if re.search(r'^\s*\\', body, re.M): sys.exit(f'{src.name}: psql meta-command')
    (out_dir / f'STEP-{step}_{title}.sql').write_text(header(step, title.replace('-', ' '), [f'Identical to {src.relative_to(root).as_posix()} (SHA-256 {sha(src)}). Reads only; changes nothing.'] + extra) + '\n' + body, encoding='utf-8')
copy(0, 'precheck-read-only', pi / '00_precheck_readonly.sql', ['The last row must say SAFE_TO_INITIALIZE before you run STEP-1.'])
copy(7, 'verify-read-only', pi / '02_verify_readonly.sql', ['Every row must say ok and the verdict READY before STEP-8.'])

(out_dir / 'STEP-8_first-super-admin.sql').write_text(header(8, 'first Super Administrator for an existing account', [
    'Makes ONE existing, email-confirmed sign-in account the first Super Administrator, using the same database function as',
    'the app\'s /setup page (claim_first_admin: under a lock, only an applicant account, only while no active Super',
    'Administrator exists). Run it only after STEP-7 says READY. EDIT ONE LINE: put the account\'s email address where it says',
    'PUT-THE-EMAIL-ADDRESS-HERE (keep the quotes). It refuses, changing nothing, if the address is not found, not confirmed,',
    'blocked or deleted, has no applicant profile, or if a Super Administrator already exists. The account, its password',
    'and its sign-in are not changed: only its profile role becomes super_admin.']) + """
do $first_admin$
declare
  v_email text := 'PUT-THE-EMAIL-ADDRESS-HERE';       -- <<< the only line to edit
  v_n int; v_id uuid; v_confirmed timestamptz; v_banned timestamptz; v_deleted timestamptz; v_role text; v_status text;
begin
  v_email := lower(btrim(v_email));
  if v_email = 'put-the-email-address-here' or v_email !~ '^[^@\\s]+@[^@\\s]+\\.[^@\\s]+$' then
    raise exception 'STOP: put the account''s email address in the line marked <<< (keep the quotes), then run again. Nothing was changed.';
  end if;
  if to_regprocedure('public.claim_first_admin(uuid)') is null or to_regclass('public.profiles') is null then
    raise exception 'STOP: DIRA LEARN is not installed yet. Run STEP-1 to STEP-7 first. Nothing was changed.';
  end if;
  if exists (select 1 from public.profiles where role = 'super_admin' and status = 'active') then
    raise exception 'STOP: an active Super Administrator already exists, so first-time setup is closed. Further administrators are appointed in the app (User Management). Nothing was changed.';
  end if;
  select count(*) into v_n from auth.users where lower(email) = v_email;
  if v_n = 0 then raise exception 'STOP: no sign-in account has the email address %. Check the spelling (Authentication -> Users). Nothing was changed.', v_email; end if;
  if v_n > 1 then raise exception 'STOP: % accounts have the email address %. Send this message to Claude. Nothing was changed.', v_n, v_email; end if;
  select id, email_confirmed_at, banned_until, deleted_at into v_id, v_confirmed, v_banned, v_deleted from auth.users where lower(email) = v_email;
  if v_confirmed is null then raise exception 'STOP: % has not confirmed its email address yet. Confirm it first (open the confirmation email). Nothing was changed.', v_email; end if;
  if v_deleted is not null then raise exception 'STOP: the account % is deleted. Nothing was changed.', v_email; end if;
  if v_banned is not null and v_banned > now() then raise exception 'STOP: the account % is blocked until %. Nothing was changed.', v_email, v_banned; end if;
  select role::text, status::text into v_role, v_status from public.profiles where id = v_id;
  if v_role is null then raise exception 'STOP: the account % has no DIRA LEARN profile (migration 36 should have created it). Send this message to Claude. Nothing was changed.', v_email; end if;
  if v_role <> 'applicant' then raise exception 'STOP: the account % already has the role %. Nothing was changed.', v_email, v_role; end if;
  if not public.claim_first_admin(v_id) then
    raise exception 'STOP: the first-administrator claim was refused (another administrator may have been created at the same moment). Nothing was changed.';
  end if;
  perform set_config('dira.first_admin', v_id::text, true);
end $first_admin$;

-- result shown in the SQL Editor
select 'The first Super Administrator is set. Sign in on the website with this account.' as result,
       u.email, p.role, p.status, u.email_confirmed_at is not null as email_confirmed
  from public.profiles p join auth.users u on u.id = p.id
 where p.id = nullif(current_setting('dira.first_admin', true), '')::uuid;
""", encoding='utf-8')
for f in sorted(out_dir.glob('STEP-*.sql')):
    print(f'{f.name}: {f.stat().st_size} bytes, sha256 {sha(f)}')
