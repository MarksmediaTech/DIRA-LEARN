#!/usr/bin/env python3
"""Generates the patch-free DIRA LEARN database baseline for NEW Supabase projects (21 Nov 2026).

Usage: python3 -I tools/baseline/build_baseline.py <project>        (needs the local PostgreSQL stand-in on /tmp:54322)

Why: the 39 incremental migrations in supabase/migrations change several functions by searching and replacing their stored
text (migrations 17, 19, 20, 23, 33, 34, 36). That failed on a real project when Windows line endings were pasted in. A new
project needs only the FINAL state, written once. This script builds the final state from the migrations (the single source
of truth), then writes it as three plain migrations in supabase/baseline/:
  ..001_baseline_schema.sql    every type, table, function, view, trigger, policy, comment and grant in schema public, in
                               dependency order (pg_dump), each object exactly once in its final form - no text patching
  ..002_baseline_platform.sql  the objects outside public: sign-up trigger on auth.users, the 6 private storage buckets and
                               their 13 policies, the realtime publication, the API pre-request check
  ..003_baseline_data.sql      the reference and curriculum data (organisation, programme, tracks, 26 sessions, 26 Draft
                               lesson plans, 24 pending topic proposals, roles, settings, email templates ...), as one-line
                               JSON per table, so line endings cannot change the data. The audit log starts empty.
Equivalence with the 39 migrations is proved by tools/baseline/baseline_check.sh (schema fingerprint and data per table).
"""
import json, pathlib, re, subprocess, sys

proj = pathlib.Path(sys.argv[1]).resolve()
out = proj / 'supabase' / 'baseline'; out.mkdir(parents=True, exist_ok=True)
V = ['20261121000001', '20261121000002', '20261121000003']
NAMES = ['dira_learn_baseline_schema', 'dira_learn_baseline_platform', 'dira_learn_baseline_data']
PG = ['-h', '/tmp', '-p', '54322', '-U', 'postgres', '-d', 'postgres']
def q(sql):
    return subprocess.run(['psql', *PG, '-X', '-tA', '-c', sql], capture_output=True, text=True, check=True).stdout.rstrip('\n')

r = subprocess.run([str(proj / 'tools' / 'db-standin' / 'db_reset.sh'), str(proj)], capture_output=True, text=True)
if r.returncode != 0 or 'applied 39 migrations + seed' not in r.stdout: sys.exit('reference build failed:\n' + r.stdout[-800:] + r.stderr[-800:])
legacy_versions = q("select count(*) from pg_class where relnamespace = 'public'::regnamespace and relkind = 'r'")

GUARD_FIRST = """do $guard$
declare n int; v text;
begin
  if pg_catalog.to_regclass('public.profiles') is not null then
    raise exception 'STOP: public.profiles already exists. The DIRA LEARN baseline is only for a NEW, empty Supabase project. Nothing was changed.';
  end if;
  select count(*) into n from pg_catalog.pg_class c join pg_catalog.pg_namespace s on s.oid = c.relnamespace where s.nspname = 'public' and c.relkind in ('r', 'p', 'v', 'm');
  if n > 0 then raise exception 'STOP: the public schema already has % table(s)/view(s). Nothing was changed.', n; end if;
  if pg_catalog.to_regclass('supabase_migrations.schema_migrations') is not null then
    execute 'select string_agg(version, '','' order by version) from supabase_migrations.schema_migrations' into v;
    if v is not null then raise exception 'STOP: this database already records migrations (%). Nothing was changed.', v; end if;
  end if;
end $guard$;
"""
def guard_after(prev):
    return f"""do $guard$
declare v text;
begin
  if pg_catalog.to_regclass('supabase_migrations.schema_migrations') is not null then
    execute 'select string_agg(version, '','' order by version) from supabase_migrations.schema_migrations' into v;
  end if;
  if v is distinct from '{prev}' then
    raise exception 'STOP: expected the baseline files before this one to be installed (history %), found %. Nothing was changed.', '{prev}', coalesce(v, 'none');
  end if;
end $guard$;
"""
def header(i, text):
    return (f"-- DIRA LEARN database baseline, file {i + 1} of 3: {NAMES[i]} (generated by tools/baseline/build_baseline.py - do not edit)\n"
            "-- The final state of migrations 01-39 + seed, for a NEW Supabase project (PostgreSQL 15-17). One transaction per file.\n"
            f"{text}\n")

# ---------------- 1. schema ----------------
dump = subprocess.run(['pg_dump', *PG, '--schema-only', '--schema=public', '--no-owner'], capture_output=True, text=True, check=True).stdout
lines = []
skip_re = re.compile(r'^(\\restrict|\\unrestrict|SET |SELECT pg_catalog\.set_config\(\'search_path\'|CREATE SCHEMA public;|COMMENT ON SCHEMA public )')
for line in dump.splitlines():
    if skip_re.match(line): continue
    lines.append(line)
schema = '\n'.join(lines).strip() + '\n'
if re.search(r'^\s*\\', schema, re.M): sys.exit('psql meta-command left in the schema dump')
if re.search(r'pg_get_functiondef|expected text not found', schema): sys.exit('text patching found in the final schema')
s1 = [header(0, '-- Every object in schema public exactly once, in final form (no text patching). Fully schema-qualified, as pg_dump writes it.'),
      GUARD_FIRST,
      "create schema if not exists supabase_migrations;\n"
      "create table if not exists supabase_migrations.schema_migrations (version text not null primary key, statements text[], name text);\n"
      "create extension if not exists pgcrypto;   -- as migration 01 (already present on Supabase)\n"
      "select pg_catalog.set_config('search_path', '', true);      -- as pg_dump: every name is schema-qualified\n"
      "select pg_catalog.set_config('check_function_bodies', 'false', true);   -- functions may refer to objects created further down\n\n",
      schema,
      f"\ninsert into supabase_migrations.schema_migrations(version, name) values ('{V[0]}', '{NAMES[0]}');\n"]
(out / f'{V[0]}_{NAMES[0]}.sql').write_text(''.join(s1), encoding='utf-8')

# ---------------- 2. platform (outside schema public) ----------------
p = [header(1, '-- Objects outside schema public: the sign-up trigger, storage buckets and policies, realtime publication, API pre-request check.'),
     guard_after(V[0])]
for t in q("select pg_get_triggerdef(oid) from pg_trigger where tgrelid = 'auth.users'::regclass and not tgisinternal order by tgname").splitlines():
    p.append(t + ';\n')
# sign-in accounts created before the installation (e.g. in the Auth dashboard) get their applicant profile, as migration 36 did
p.append("insert into public.profiles(id, role, status) select u.id, 'applicant', 'active' from auth.users u\n"
         " where not exists (select 1 from public.profiles p where p.id = u.id) on conflict (id) do nothing;\n")
for row in q("select row_to_json(b)::text from (select id, name, public, file_size_limit, allowed_mime_types from storage.buckets order by id) b").splitlines():
    b = json.loads(row)
    mimes = 'null' if b['allowed_mime_types'] is None else "array[" + ', '.join("'" + m.replace("'", "''") + "'" for m in b['allowed_mime_types']) + "]::text[]"
    size = 'null' if b['file_size_limit'] is None else str(b['file_size_limit'])
    p.append(f"insert into storage.buckets(id, name, public, file_size_limit, allowed_mime_types) values ('{b['id']}', '{b['name']}', {str(b['public']).lower()}, {size}, {mimes});\n")
for row in q("select row_to_json(x)::text from (select policyname, permissive, cmd, roles::text[] as roles, qual, with_check from pg_policies where schemaname = 'storage' and tablename = 'objects' order by policyname) x").splitlines():
    x = json.loads(row)
    sql = f'create policy "{x["policyname"]}" on storage.objects as {x["permissive"].lower()} for {x["cmd"].lower()} to {", ".join(x["roles"])}'
    if x['qual']: sql += f' using ({x["qual"]})'
    if x['with_check']: sql += f' with check ({x["with_check"]})'
    p.append(' '.join(sql.split()) + ';\n')
for t in q("select schemaname || '.' || tablename from pg_publication_tables where pubname = 'supabase_realtime' order by 1").splitlines():
    p.append(f"alter publication supabase_realtime add table {t};\n")
p.append("""do $$
begin
  execute 'alter role authenticator set pgrst.db_pre_request = ''public.check_request''';
  notify pgrst, 'reload config';
exception when insufficient_privilege then
  raise warning 'Could not register check_request() as the API pre-request function (no permission). Run in the SQL Editor: alter role authenticator set pgrst.db_pre_request = ''public.check_request''; notify pgrst, ''reload config'';';
end $$;
""")
p.append(f"insert into supabase_migrations.schema_migrations(version, name) values ('{V[1]}', '{NAMES[1]}');\n")
(out / f'{V[1]}_{NAMES[1]}.sql').write_text(''.join(p), encoding='utf-8')

# ---------------- 3. data ----------------
# Start empty in a new project: the audit log, and the staging/backup copies that only the legacy migration path uses
# (V13 loader staging tables and the repair backups of migrations 33-38). The app never reads them (checked 21 Nov 2026).
SKIP_DATA = {'audit_logs', 'curriculum_v13_sessions', 'curriculum_v13_tracks', 'curriculum_v13_1_sessions', 'curriculum_v13_1_previous',
             'curriculum_v13_2_sessions', 'curriculum_v13_2_previous', 'security_fix_33_backup', 'security_fix_34_backup',
             'file_scanning_35_backup', 'profile_repair_36_backup', 'grants_38_backup'}
tables = [t for t in q("""select c.relname from pg_class c where c.relnamespace = 'public'::regnamespace and c.relkind = 'r' order by c.relname""").splitlines()]
d = [header(2, '-- Reference and curriculum data as one-line JSON per table (line endings cannot change it). The tables\' own triggers are\n'
              '-- paused while each table is loaded (ALTER TABLE ... DISABLE TRIGGER USER: allowed for the table owner, the role that ran\n'
              '-- the schema file; foreign keys stay enforced), so the rows are stored exactly as in the reference build. Not\n'
              '-- session_replication_role: setting it needs superuser rights, which the Supabase SQL Editor does not have (21 Nov 2026).'),
     guard_after(V[0] + ',' + V[1])]
# load in foreign-key order (parents first), because foreign keys stay enforced
fks = [tuple(l.split('|')) for l in q("select conrelid::regclass::text, confrelid::regclass::text from pg_constraint where contype = 'f' and connamespace = 'public'::regnamespace and conrelid <> confrelid").splitlines() if l]
ordered, seen = [], set()
def visit(t, path=()):
    if t in seen: return
    if t in path: sys.exit(f'foreign-key cycle at {t}')
    for child, parent in fks:
        if child == t and parent in tables: visit(parent, path + (t,))
    seen.add(t); ordered.append(t)
for t in tables: visit(t)
tables = ordered
total = 0
for t in tables:
    if t in SKIP_DATA: continue
    n = int(q(f"select count(*) from public.{t}"))
    if n == 0: continue
    cols = q(f"""select string_agg(quote_ident(attname), ', ' order by attnum) from pg_attribute where attrelid = 'public.{t}'::regclass and attnum > 0 and not attisdropped and attgenerated = ''""")
    ident = q(f"select count(*) from pg_attribute where attrelid = 'public.{t}'::regclass and attidentity = 'a'") != '0'
    data = q(f"select coalesce(json_agg(row_to_json(x) order by x::text), '[]')::text from (select {cols} from public.{t}) x")
    if '$dira_json$' in data or '\n' in data or '\r' in data: sys.exit(f'{t}: data cannot be embedded safely')
    d.append(f"alter table public.{t} disable trigger user; insert into public.{t}({cols}){' overriding system value' if ident else ''} select {cols} from jsonb_populate_recordset(null::public.{t}, $dira_json${data}$dira_json$::jsonb); alter table public.{t} enable trigger user;\n")
    total += n
for seq, val, called in (l.split('|') for l in q("select sequencename, last_value, 't' from pg_sequences where schemaname = 'public' and last_value is not null and sequencename <> 'audit_logs_id_seq'").splitlines() if l):
    d.append(f"select setval('public.{seq}', {val}, true);\n")
# ---- Data API privileges, exactly as in the reference (found 21 Nov 2026 on a real project): Supabase still applies default
# privileges to tables the SQL Editor's role creates in public (there: TRUNCATE, REFERENCES and TRIGGER for anon, authenticated
# and service_role on every table and view). The schema file only ADDS the intended grants, so those extra privileges stayed and
# STEP-5 check 16 failed. This block removes every privilege of the API roles on the tables, views and sequences of public and
# re-applies exactly the grants of migration 38, then checks the result. Functions, the schema, data and policies are untouched.
grant_lines = [l for l in schema.splitlines() if re.match(r'^GRANT [A-Z,]+ ON (TABLE|SEQUENCE) public\.\S+ TO (anon|authenticated|service_role);$', l)]
other = [l for l in schema.splitlines() if re.match(r'^(GRANT|REVOKE) .* ON (TABLE|SEQUENCE) ', l) and l not in grant_lines]
if other: sys.exit('unexpected table/sequence privilege statements in the dump: ' + '; '.join(other[:3]))
exp = {r.split('|')[0]: r.split('|')[1:] for r in q("""select grantee, count(distinct table_name), count(*) from information_schema.table_privileges
          where table_schema = 'public' and grantee in ('anon', 'authenticated', 'service_role') group by 1""").splitlines()}
if 'anon' in exp: sys.exit('reference grants table privileges to anon')
ea, eat = exp['authenticated']; es, est = exp['service_role']
seq_exp = q("select count(*) from information_schema.usage_privileges where object_schema = 'public' and object_type = 'SEQUENCE' and grantee in ('anon', 'authenticated', 'service_role')")
API_GRANTS = ("-- >>> api-grants (generated by tools/baseline/build_baseline.py)\n"
"do $revoke_api$\ndeclare r record;\nbegin\n"
"  for r in select c.oid::regclass as rel from pg_catalog.pg_class c where c.relnamespace = 'public'::regnamespace and c.relkind in ('r', 'p', 'v', 'm', 'f', 'S') loop\n"
"    execute format('revoke all on table %s from anon, authenticated, service_role, public', r.rel);\n"
"  end loop;\nend $revoke_api$;\n"
+ '\n'.join(grant_lines) + '\n' +
f"""do $check_api$
declare n_anon int; n_bad int; n_nopol int; a_tab int; a_priv int; s_tab int; s_priv int; n_seq int;
begin
  select count(*) into n_anon from information_schema.table_privileges where table_schema = 'public' and grantee in ('anon', 'PUBLIC');
  select count(*) into n_bad from information_schema.table_privileges where table_schema = 'public' and grantee in ('anon', 'authenticated', 'service_role')
     and privilege_type in ('TRUNCATE', 'REFERENCES', 'TRIGGER');
  select count(*) into n_nopol from information_schema.table_privileges tp
    join pg_catalog.pg_class c on c.relname = tp.table_name and c.relnamespace = 'public'::regnamespace and c.relkind in ('r', 'p')
   where tp.table_schema = 'public' and tp.grantee = 'authenticated'
     and not exists (select 1 from pg_catalog.pg_policies p where p.schemaname = 'public' and p.tablename = tp.table_name and p.permissive = 'PERMISSIVE'
                      and p.roles && array['authenticated', 'public']::name[] and (p.cmd = 'ALL' or p.cmd = tp.privilege_type));
  select count(distinct table_name), count(*) into a_tab, a_priv from information_schema.table_privileges where table_schema = 'public' and grantee = 'authenticated';
  select count(distinct table_name), count(*) into s_tab, s_priv from information_schema.table_privileges where table_schema = 'public' and grantee = 'service_role';
  select count(*) into n_seq from information_schema.usage_privileges where object_schema = 'public' and object_type = 'SEQUENCE' and grantee in ('anon', 'authenticated', 'service_role');
  if n_anon <> 0 or n_bad <> 0 or n_nopol <> 0 or a_tab <> {ea} or a_priv <> {eat} or s_tab <> {es} or s_priv <> {est} or n_seq <> {seq_exp} then
    raise exception 'API privileges are not as intended (signed-out %, TRUNCATE/REFERENCES/TRIGGER %, without policy %, signed-in %/% (want {ea}/{eat}), service role %/% (want {es}/{est}), sequences % (want {seq_exp})). Nothing was changed.',
      n_anon, n_bad, n_nopol, a_tab, a_priv, s_tab, s_priv, n_seq;
  end if;
end $check_api$;
-- <<< api-grants
""")
d.append(API_GRANTS)
d.append(f"insert into supabase_migrations.schema_migrations(version, name) values ('{V[2]}', '{NAMES[2]}');\n")
(out / f'{V[2]}_{NAMES[2]}.sql').write_text(''.join(d), encoding='utf-8')

for f in sorted(out.glob('*.sql')):
    print(f'{f.name}: {f.stat().st_size} bytes')
print(f'baseline: {legacy_versions} tables, {total} data rows (empty: {len(SKIP_DATA)} legacy/audit tables)')
