#!/usr/bin/env python3
"""Prepare the approved original DIRA Foundation photographs for the site (post-audit priority 6).

Usage:  python3 tools/photos/prepare.py <folder with the original photos> <project folder>

For every photo in tools/photos/photos.yaml with approved: true it
  * turns the image upright (camera orientation) and converts it to sRGB,
  * removes all metadata (camera data, GPS location, names) - nothing about where or when it was taken is published,
  * writes WebP copies 640, 1280 and 1920 pixels wide to public/photos/ - the WHOLE picture, never cropped, never stretched
    (the height follows the original proportions) and never enlarged beyond the original,
  * writes src/lib/photos.generated.ts, which the site uses instead of the website copies.
It stops without writing anything if a listed photo is missing, unapproved photos are skipped, and an original smaller than
1280 px wide is refused (it would look blurred on large screens). The site crops only on screen, with `focal` as the centre.
"""
import io, os, sys, json
import yaml
from PIL import Image, ImageOps

WIDTHS = (640, 1280, 1920)
MIN_WIDTH = 1280

def main(src_dir, proj):
    cfg = yaml.safe_load(open(os.path.join(proj, 'tools', 'photos', 'photos.yaml'), encoding='utf8'))
    todo = [p for p in cfg['photos'] if p.get('approved') is True]
    if not todo:
        print('No photo is marked approved: true in tools/photos/photos.yaml - nothing written.'); return 1
    prepared, problems = [], []
    for p in todo:
        path = os.path.join(src_dir, p['file'])
        if not os.path.isfile(path): problems.append(f"{p['id']}: {p['file']} not found in {src_dir}"); continue
        im = ImageOps.exif_transpose(Image.open(path))
        if im.mode not in ('RGB', 'RGBA'): im = im.convert('RGB')
        if 'icc_profile' in im.info:   # convert to sRGB so colours look the same in every browser
            from PIL import ImageCms
            im = ImageCms.profileToProfile(im, ImageCms.ImageCmsProfile(io.BytesIO(im.info['icc_profile'])), ImageCms.createProfile('sRGB'), outputMode='RGB')
        im = im.convert('RGB')
        if im.width < MIN_WIDTH: problems.append(f"{p['id']}: only {im.width} px wide; supply an original at least {MIN_WIDTH} px wide"); continue
        outs = []
        for w in WIDTHS:
            if w > im.width: continue                                   # never enlarge
            h = round(im.height * w / im.width)                          # keep the proportions: no stretching, no cropping
            data = io.BytesIO(); im.resize((w, h), Image.LANCZOS).save(data, 'WEBP', quality=82, method=6)   # saved without metadata
            outs.append((w, h, data.getvalue()))
        prepared.append((p, im.width, im.height, outs))
    if problems:
        print('STOPPED, nothing written:'); [print('  - ' + x) for x in problems]; return 2
    out_dir = os.path.join(proj, 'public', 'photos'); os.makedirs(out_dir, exist_ok=True)
    for f in os.listdir(out_dir):
        if f.endswith('.webp'): os.remove(os.path.join(out_dir, f))
    entries = []
    for p, w0, h0, outs in prepared:
        for w, h, data in outs:
            open(os.path.join(out_dir, f"{p['id']}-{w}.webp"), 'wb').write(data)
        entries.append({'id': p['id'], 'alt': p['alt'], 'focal': p.get('focal', '50% 50%'), 'widths': [w for w, _, _ in outs], 'width': w0, 'height': h0})
        print(f"{p['id']}: original {w0}x{h0} -> " + ', '.join(f'{w}x{h} ({len(d)//1024} KB)' for w, h, d in outs))
    ts = ('// Generated by tools/photos/prepare.py from the approved original DIRA Foundation photographs. Do not edit by hand.\n'
          "import type { LocalPhoto } from './photoSources';\n\n"
          f'export const LOCAL_PHOTOS: readonly LocalPhoto[] = {json.dumps(entries, indent=2, ensure_ascii=False)};\n')
    open(os.path.join(proj, 'src', 'lib', 'photos.generated.ts'), 'w', encoding='utf8').write(ts)
    print(f'{len(entries)} photos prepared in public/photos; src/lib/photos.generated.ts updated.')
    return 0

if __name__ == '__main__':
    if len(sys.argv) != 3: print(__doc__); sys.exit(1)
    sys.exit(main(sys.argv[1], sys.argv[2]))
