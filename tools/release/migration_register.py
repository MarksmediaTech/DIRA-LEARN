#!/usr/bin/env python3
"""The one authoritative migration register, generated from the migration files themselves.

  python3 -I tools/release/migration_register.py <project>           write docs/deployment/MIGRATION_REGISTER.md
  python3 -I tools/release/migration_register.py <project> --check   fail if the register is stale or anything disagrees

Checks: file names (<14 digits>_<name>.sql), numbering contiguous from 01 with no gaps or duplicates, every rollback file
names an existing migration, both initialization bundles contain exactly the right migrations byte for byte (by
SHA-256), the verification SQL expects the same count, and the deployment docs state the same range (the old docs said
36 when there were 37).
"""
import hashlib, pathlib, re, sys

root = pathlib.Path(sys.argv[1]).resolve(); check = '--check' in sys.argv
mig = sorted((root / 'supabase' / 'migrations').glob('*.sql'))
rb = {p.name for p in (root / 'supabase' / 'rollback').glob('*.sql')}
out = root / 'docs' / 'deployment' / 'MIGRATION_REGISTER.md'
problems = []
pat = re.compile(r'^(\d{14})_([a-z0-9_]+)\.sql$')
rows = []
for i, p in enumerate(mig, 1):
    m = pat.match(p.name)
    if not m: problems.append(f'bad migration file name: {p.name}'); continue
    v, name = m.groups()
    if int(v) != 20260101000000 + i: problems.append(f'numbering: position {i} is {v} (expected {20260101000000 + i}); gap, duplicate or wrong order')
    first = next((l[3:].strip() for l in p.read_text(encoding='utf-8').splitlines() if l.startswith('-- ') and len(l) > 6), '')
    purpose = re.sub(r'^Migration \d+\s*[-–:]\s*', '', first)[:150].replace('|', '/')
    down = f'{v}_{name}_down.sql'
    rows.append((i, v, name, purpose, down in rb, hashlib.sha256(p.read_bytes()).hexdigest()))
n = len(rows)
for f in sorted(rb):
    m = re.match(r'^(\d{14})_([a-z0-9_]+)_down\.sql$', f)
    if not m or not (root / 'supabase' / 'migrations' / f'{m.group(1)}_{m.group(2)}.sql').exists():
        problems.append(f'rollback without a matching migration: {f}')

pi = root / 'supabase' / 'production_init'
bundle = (pi / '01_initialize_production.sql')
if bundle.exists():
    listed = re.findall(r'^--\s+([0-9a-f]{64})\s+supabase/migrations/(\S+)$', bundle.read_text(encoding='utf-8'), re.M)
    want = [(r[5], f'{r[1]}_{r[2]}.sql') for r in rows]
    if listed != want: problems.append(f'01_initialize_production.sql does not contain migrations 01-{n:02d} byte for byte (regenerate with build_bundle.py)')
cont = pi / '01b_continue_after_37.sql'
if cont.exists() and n >= 38:
    listed = re.findall(r'^--\s+([0-9a-f]{64})\s+supabase/migrations/(\S+)$', cont.read_text(encoding='utf-8'), re.M)
    if listed != [(r[5], f'{r[1]}_{r[2]}.sql') for r in rows[37:]]:
        problems.append('01b_continue_after_37.sql does not contain migrations 38 onward byte for byte (regenerate with build_bundle.py)')
verify = pi / '02_verify_readonly.sql'
if verify.exists() and f'generate_series(1, {n})' not in verify.read_text(encoding='utf-8'):
    problems.append(f'02_verify_readonly.sql does not expect {n} migrations')
doc = root / 'docs' / 'deployment' / 'PRODUCTION_DB_INITIALIZATION.md'
if doc.exists():
    t = doc.read_text(encoding='utf-8')
    if f'01–{n:02d}' not in t: problems.append(f'PRODUCTION_DB_INITIALIZATION.md never states the range 01–{n:02d}')
    for k in sorted(set(re.findall(r'migrations? `?01`?[–-]`?(\d\d)`?\b', t))):
        if k not in (f'{n:02d}', '36', '37'): problems.append(f'PRODUCTION_DB_INITIALIZATION.md mentions a migration range ending at {k}')

lines = ['# Migration register (generated - do not edit by hand)', '',
         f'Generated by `tools/release/migration_register.py` from `supabase/migrations/`. **{n} migrations, 01–{n:02d}**, applied in this order on every database.',
         'CI and `tools/check-all.sh` run this script with `--check`; it fails on a gap, a duplicate, a wrong order, a rollback without a',
         'migration, a bundle that differs from the files, or documentation that states another count.', '',
         'Rollback scripts exist for the migrations marked "yes". Migrations 01–13, 15 and 17–22 are the foundation and have none; undo them by restoring a backup.', '',
         '| # | Version | File | Purpose (first line of the file) | Rollback | SHA-256 (first 12) |', '|---|---|---|---|---|---|']
for i, v, name, purpose, has_rb, h in rows:
    lines.append(f'| {i:02d} | {v} | `{v}_{name}.sql` | {purpose} | {"yes" if has_rb else "-"} | `{h[:12]}` |')
lines += ['', 'Then `supabase/seed.sql` (reference data and curriculum drafts; idempotent).', '']
text = '\n'.join(lines)
if check:
    if not out.exists() or out.read_text(encoding='utf-8') != text: problems.append('MIGRATION_REGISTER.md is stale (run the script without --check)')
else:
    out.write_text(text, encoding='utf-8')
print(f'migration register: {n} migrations (01-{n:02d}), {sum(r[4] for r in rows)} with rollback; {len(problems)} problems')
for p in problems: print('  PROBLEM ' + p)
sys.exit(1 if problems else 0)
