// Generates the translucent-purple panel theme and the glowing multicolour border (23 Nov 2026) as plain CSS and writes it between the
// markers in src/index.css. Plain CSS (not a Tailwind plugin) so it behaves the same in Tailwind 3 and in the test harness.
// Usage: node tools/ui-theme/generate-panel-css.mjs [--check]     (--check: fail if src/index.css is out of date)
import fs from 'node:fs'; import path from 'node:path';
const proj = path.resolve(path.dirname(new URL(import.meta.url).pathname), '../..');
const START = '/* >>> PANEL THEME (generated by tools/ui-theme/generate-panel-css.mjs: edit the generator, not this block) */';
const END = '/* <<< PANEL THEME */';

// Every card that already uses the app's card style (rounded-card + a purple border) inside the page content (<main>), plus .dira-panel.
// .dira-plain on an element or an ancestor opts out (Chat screen). Welcome panel: .dira-welcome (own rules below).
const PANEL = ':is(.dira-panel, main .rounded-card.border-purple-100, main .rounded-card.border-purple-200)';
const THEMED = `${PANEL}:not(.dira-plain, .dira-plain *)`;
const INNER = `${THEMED} ${PANEL}`;
const LIGHT = ['bg-white', 'bg-purple-50', 'bg-purple-100', 'bg-orange-50', 'bg-amber-50', 'bg-amber-100', 'bg-red-50', 'bg-green-100', 'bg-gray-100'];
const LIGHT_SEL = LIGHT.map((c) => `.${c}`).join(', ');
// [class, colour on the purple panel, original colour on a light surface inside a panel]
const TEXT = [
  ['text-ink', '#F6F0FC', '#21173A'], ['text-dira-deep', '#F6F0FC', '#1E0B3D'], ['text-purple-900', '#F6F0FC', '#2D1A54'],
  ['text-purple-700', '#DCC8F6', '#4F2A8F'], ['text-purple-600', '#DCC8F6', '#6537B3'], ['text-purple-500', '#DCC8F6', '#7B4FC9'],
  ['text-dira-royal', '#DCC8F6', '#61358A'], ['text-dira-primary', '#DCC8F6', '#452064'], ['text-dira-logo', '#DCC8F6', '#4C1D95'],
  ['text-ink\\/80', 'rgb(246 240 252 / .9)', 'rgb(33 23 58 / .8)'], ['text-ink\\/70', 'rgb(246 240 252 / .86)', 'rgb(33 23 58 / .7)'],
  ['text-ink\\/60', 'rgb(246 240 252 / .8)', 'rgb(33 23 58 / .6)'], ['text-ink\\/50', 'rgb(246 240 252 / .75)', 'rgb(33 23 58 / .5)'],
  ['text-ink\\/40', 'rgb(246 240 252 / .72)', 'rgb(33 23 58 / .4)'],
  ['text-dira-deep\\/80', 'rgb(246 240 252 / .88)', 'rgb(30 11 61 / .8)'], ['text-dira-deep\\/70', 'rgb(246 240 252 / .86)', 'rgb(30 11 61 / .7)'],
  ['text-dira-deep\\/60', 'rgb(246 240 252 / .8)', 'rgb(30 11 61 / .6)'], ['text-dira-deep\\/40', 'rgb(246 240 252 / .72)', 'rgb(30 11 61 / .4)'],
  ['text-danger', '#FFB4AB', '#B3261E'], ['text-ok', '#8FE3B3', '#1F7A4D'], ['text-warn', '#FFCB85', '#B45309'], ['text-dira-orange', '#FF9A4D', '#FE7613'],
  ['text-green-800', '#8FE3B3', '#166534'], ['text-red-700', '#FFB4AB', '#B91C1C'], ['text-amber-800', '#FFCB85', '#92400E'],
];
const RING = 'linear-gradient(120deg, #4285F4 0%, #EA4335 34%, #FBBC05 67%, #34A853 100%)';
const MASK = { '-webkit-mask': 'linear-gradient(#000 0 0) content-box, linear-gradient(#000 0 0)', '-webkit-mask-composite': 'xor', mask: 'linear-gradient(#000 0 0) content-box exclude, linear-gradient(#000 0 0)' };
const glow = (a, b, c, d, r, s) => `-${a}px -${b}px ${r}px -${s}px rgb(66 133 244 / ${c}), ${a}px -${b}px ${r}px -${s}px rgb(234 67 53 / ${d}), ${a}px ${a}px ${r}px -${s}px rgb(251 188 5 / ${d - 0.02}), -${a}px ${a}px ${r}px -${s}px rgb(52 168 83 / ${c - 0.06})`;

const rules = [];                                  // [selector, declarations]
const rule = (sel, decl) => rules.push([sel, decl]);

rule(`:where(${PANEL})`, { position: 'relative' });   // zero specificity: a panel that is absolute or sticky keeps that
rule(THEMED, {
  background: 'radial-gradient(120% 80% at 0% 0%, rgb(124 77 196 / .30), transparent 60%), linear-gradient(160deg, rgb(58 28 104 / .88), rgb(30 11 61 / .86))',
  'border-color': 'rgb(255 255 255 / .06)', color: '#F3ECFB',
  'box-shadow': `0 0 0 1px rgb(255 255 255 / .04), ${glow(5, 3, '.34', '.26', 14, 6)}`,
});
rule(`${THEMED}::before`, { content: '""', position: 'absolute', inset: '0', 'border-radius': 'inherit', padding: '1.5px', background: RING, ...MASK, opacity: '.9', 'pointer-events': 'none', 'z-index': '1' });
rule(INNER, { background: 'rgb(255 255 255 / .05)', 'box-shadow': 'none', 'border-color': 'rgb(255 255 255 / .16)' });
rule(`${INNER}::before`, { display: 'none' });
for (const [cls, onPanel] of TEXT) rule(`${THEMED} .${cls}`, { color: onPanel });
rule(`${THEMED} :is(h1, h2, h3, h4)`, { color: '#F6F0FC' });
rule(`${THEMED} a:not([class])`, { color: '#DCC8F6' });
rule(`${THEMED} .border-purple-100, ${THEMED}.divide-purple-100 > *, ${THEMED} .divide-purple-100 > *`, { 'border-color': 'rgb(255 255 255 / .14)' });
rule(`${THEMED} .border-purple-200`, { 'border-color': 'rgb(255 255 255 / .32)' });
rule(`${THEMED} :is(.bg-purple-600, .bg-purple-700)`, { 'box-shadow': '0 0 0 1px rgb(255 255 255 / .22)' });
// light surfaces inside a panel keep dark text
rule(`${THEMED} :is(${LIGHT_SEL}, input:not([type=checkbox], [type=radio], [type=range]), select, textarea)`, { color: '#21173A' });
for (const [cls, , original] of TEXT) rule(`${THEMED} :is(${LIGHT_SEL}, input, select, textarea) .${cls}, ${THEMED} :is(${LIGHT_SEL}).${cls}`, { color: original });
// translucent light tints inside a panel become soft tints of the panel (a translucent light surface over purple would be a muddy mid-tone)
rule(`${THEMED} :is(.bg-purple-50\\/40, .bg-purple-50\\/50, .bg-purple-50\\/60, .bg-purple-50\\/70, .bg-dira-lavender\\/50, .bg-dira-lavender\\/60)`, { 'background-color': 'rgb(255 255 255 / .09)' });
rule(`${THEMED} .bg-orange-50\\/60`, { 'background-color': 'rgb(254 118 19 / .16)' });
rule(`${THEMED} :is(input:not([type=checkbox], [type=radio], [type=range], [type=file]), select, textarea)`, { 'background-color': 'rgb(255 255 255 / .97)', 'border-color': 'rgb(255 255 255 / .55)' });
rule(`${THEMED} :is(input, textarea)::placeholder`, { color: 'rgb(33 23 58 / .5)' });
rule(`${THEMED} select option`, { color: '#21173A', 'background-color': '#FFFFFF' });
rule(`${THEMED} :is(input, select, textarea):disabled`, { opacity: '.7' });
rule(`${THEMED} :is(.recharts-text, .recharts-cartesian-axis-tick-value, .recharts-legend-item-text)`, { fill: '#E9DDF3', color: '#E9DDF3' });
rule(`${THEMED} .recharts-cartesian-grid line`, { stroke: 'rgb(255 255 255 / .16)' });
// welcome panel (live photographs)
rule('.dira-welcome', { position: 'relative', 'box-shadow': `0 0 0 1px rgb(255 255 255 / .05), ${glow(8, 4, '.5', '.4', 26, 8)}` });
rule('.dira-welcome::before', { content: '""', position: 'absolute', inset: '0', 'border-radius': 'inherit', padding: '2.5px', 'pointer-events': 'none', 'z-index': '30',
  background: 'linear-gradient(120deg, #4285F4, #EA4335, #FBBC05, #34A853, #4285F4)', 'background-size': '300% 300%', animation: 'dira-ring-flow 18s linear infinite', ...MASK });

const block = (sel, decl) => `${sel} { ${Object.entries(decl).map(([k, v]) => `${k}: ${v};`).join(' ')} }`;
const css = [
  START,
  '@keyframes dira-ring-flow { 0% { background-position: 0% 50%; } 100% { background-position: 300% 50%; } }',
  '@media screen {', ...rules.map(([s, d]) => '  ' + block(s, d)), '}',
  `@media screen and (max-width: 640px) { ${block(THEMED, { 'box-shadow': `0 0 0 1px rgb(255 255 255 / .04), ${glow(3, 2, '.34', '.26', 9, 5)}` })} }`,
  '@media (prefers-reduced-motion: reduce) { .dira-welcome::before { animation: none; } }',
  END,
].join('\n');

const file = path.join(proj, 'src/index.css'); let cur = fs.readFileSync(file, 'utf8');
const a = cur.indexOf(START), b = cur.indexOf(END);
const next = a >= 0 && b > a ? cur.slice(0, a) + css + cur.slice(b + END.length) : cur.replace(/\s*$/, '\n\n') + css + '\n';
if (process.argv.includes('--check')) { if (next !== cur) { console.error('src/index.css is out of date: run node tools/ui-theme/generate-panel-css.mjs'); process.exit(1); } console.log('panel theme CSS is in sync'); }
else { fs.writeFileSync(file, next); console.log('panel theme written to src/index.css,', css.length, 'bytes'); }
